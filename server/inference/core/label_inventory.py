def _selftest() -> None:
    import tempfile
    import numpy as np

    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        chats = td / "chats"
        chats.mkdir()
        mem = td / "memory"
        mem.mkdir()

        def transcript(stem, model, adapter, n, with_series=True):
            exs = []
            for i in range(n):
                ex = {"exchange_id": f"{stem}-e{i}", "user_prompt": "u", "assistant_response": "a"}
                if with_series:
                    ex["tension"] = {"token_ids": [1, 2], "entropies": [1, 1], "margins": [0.9, 0.9]}
                exs.append(ex)
            (chats / f"{stem}.json").write_text(json.dumps({
                "timestamp": stem, "model_id": model, "adapter_id": adapter, "exchanges": exs}))

        transcript("20260901_000000", "m1", "/somewhere/models/a1", 4)
        transcript("20260902_000000", "m1", "a1", 3, with_series=False)
        transcript("20260903_000000", "m2", "", 2)
        # sidecars: chat 1 fully reflected (keep, revise, keep-banned, none), chat 3 one keep
        (chats / "20260901_000000.state.json").write_text(json.dumps({
            "reflected_at": "x", "exchanges": {
                "0": {"verdict": "keep"}, "1": {"verdict": "revise", "locked": True},
                "2": {"verdict": "keep", "banned": True}}}))
        (chats / "20260903_000000.state.json").write_text(json.dumps({
            "exchanges": {"0": {"verdict": "keep"}}}))
        # a stray non-transcript json must not be counted
        (chats / "20260901_000000.summary.json").write_text("{}")
        # hidden capture for chat 1 exchanges 0 and 1, with an axis projection
        cap = {"positions": [0, 1], "residuals": {2: np.zeros((2, 4), dtype=np.float16)},
               "axes": {"pain": [0.1, 0.2]}, "n_tokens": 2, "layers": [2], "hidden_dim": 4}
        for i in (0, 1):
            hidden_capture.write_sidecar(chats / "20260901_000000.json", f"20260901_000000-e{i}",
                                         cap, model_id="m1", adapter_id="a1")
        # op-log: three asks (search, user, meta), one resolved, one surfaced twice; a fact
        (mem / "rag_memory.jsonl").write_text("\n".join(json.dumps(r) for r in [
            {"op": "insert", "key": "q1", "kind": "ask", "ask_kind": "search"},
            {"op": "insert", "key": "q2", "kind": "ask", "ask_kind": "user"},
            {"op": "insert", "key": "q3", "kind": "ask", "ask_kind": "meta"},
            {"op": "insert", "key": "f1", "kind": "fact"},
            {"op": "surface", "key": "q2"}, {"op": "surface", "key": "q2"},
            {"op": "evict", "key": "q1"},
        ]))

        rep = build(chats, mem, None, current_model="m1", current_adapter="a1", min_labeled=3)
        c = rep["chats"]
        assert c["transcripts"] == 3 and c["exchanges"] == 9, (c["transcripts"], c["exchanges"])
        g = c["groups"][("m1", "a1")]
        assert g["transcripts"] == 2 and g["exchanges"] == 7 and g["reflected"] == 1
        assert g["verdicts"]["keep"] == 2 and g["verdicts"]["revise"] == 1 and g["verdicts"][""] == 4
        assert g["banned"] == 1 and g["locked"] == 1
        assert g["tension"] == 4 and g["hidden"] == 2 and g["axes"] == 2    # axis members in the sidecar
        assert g["labeled"] == 2 and g["labeled_hidden"] == 2      # keep+revise, ban excluded
        g2 = c["groups"][("m2", "")]
        assert g2["labeled"] == 1 and g2["labeled_hidden"] == 0 and g2["base"] == 0
        assert c["verdict_values"] == ["keep", "revise"]
        a = rep["asks"]
        assert a["live"] == {"user": 1, "meta": 1} and a["resolved"] == {"search": 1}
        assert a["surface_hist"] == {"0": 1, "2": 1}
        r = rep["readiness"]
        assert r["identity"]["labeled"] == 3 and r["identity"]["current_labeled"] == 2
        assert r["identity"]["verdict"].startswith("LABELS EXIST BUT UNDER OTHER WEIGHTS")
        rep2 = build(chats, mem, None, current_model="m1", current_adapter="/else/a1/", min_labeled=2)
        assert rep2["readiness"]["identity"]["verdict"].startswith("READY")
        assert rep2["readiness"]["identity"]["revise_share"] == 1 / 3 and rep2["readiness"]["identity"]["balance_ok"]
        assert "CLASS BALANCE" not in rep2["readiness"]["identity"]["verdict"]
