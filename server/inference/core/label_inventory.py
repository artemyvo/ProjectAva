"""Label inventory — the Track B census (AVA_REWARD_LOOP.md §7 item 4).

One table that answers "can the probe experiment (§4.3) run yet?" from what the box
already holds, without a model:

  * **Identity-channel labels.** Every reflected exchange carries a verdict in its
    ``.state.json`` sidecar (``keep`` / ``revise`` — `chat_sidecar.write_verdict`).
    ``revised ∈ {0,1}`` is that verdict; a banned exchange is not a label. Counted per
    (model, adapter) because a label is only usable with the hidden states of the
    weights that produced the reply.
  * **Hidden-state captures.** Which of those exchanges have residuals in the
    transcript's ``.hidden.npz`` (`core/hidden_capture.py`). A label without a
    capture is still useful: for a chat generated by the CURRENTLY configured
    model + adapter the residuals can be recomputed by a teacher-forced forward pass
    over the stored tokens (§4.3 step 1) — the same weights give the same states.
    For any other weights they cannot, and the label waits for a probe trained on
    those weights.
  * **Epistemic-channel labels.** ASK records by kind and ``surface_count`` from the
    reflection op-log, and ASK attempts with judge verdicts (Track A, §3) — zero
    until items 7–11 exist. Reset tests (§3.7) likewise.

Readiness follows §4.1 of the note: several hundred labelled exchanges (``--min-labeled``,
default 300), ≥ 100 ASK attempts with verdicts, ≥ 10 reset tests. The verdict lines
at the bottom say which precondition holds, and for the identity channel whether the
shortfall is labels (wait for reflection) or captures (backfill, or wait for new chats).

Read-only. GPU-free. ``python -m core.label_inventory [--chats DIR] [--memory DIR]
[--json] [--min-labeled N]`` from ``server/inference``; the ``__main__`` with
``--selftest`` builds a throwaway corpus and checks the counts.
"""

from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Optional

from core.chat_sidecar import iter_chat_json_files, sidecar_path_for
from core import hidden_capture

# §4.1 thresholds: "≥ several hundred exchanges with revised ∈ {0,1}, ≥ 100 ASK attempts
# with verdicts, ≥ 10 reset tests."
DEFAULT_MIN_LABELED = 300
MIN_ASK_ATTEMPTS = 100
MIN_RESET_TESTS = 10

LABEL_VERDICTS = ("keep", "revise")
# Below this share of `revise` among labelled exchanges the identity probe has too few
# positives to learn from (a 1% positive class is a constant predictor's AUC).
MIN_REVISE_SHARE = 0.05


def adapter_name(adapter_id: str) -> str:
    """The adapter's identity is its directory name (`adapter-<run_id>`): a transcript
    records what the box was configured with, which may be a bare name or an absolute
    path, and the config on another checkout may hold a different path to the same
    adapter. "" stays "" (base)."""
    a = str(adapter_id or "").strip().rstrip("/\\")
    return Path(a).name if a else ""


